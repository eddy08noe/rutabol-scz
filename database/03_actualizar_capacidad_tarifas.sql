-- Instala tarifa base solo si la línea todavía no tiene una tarifa vigente
-- en la categoría. Los administradores podrán registrar cambios futuros.
INSERT INTO tarifas (linea_id, categoria, importe, vigente_desde)
SELECT l.id, t.categoria, t.importe, DATE '2026-10-05'
  FROM lineas l
 CROSS JOIN (VALUES
   ('GENERAL', 3.50::NUMERIC), ('MENOR_12', 0.50::NUMERIC),
   ('ESCOLAR_PRIMARIA', 0.50::NUMERIC), ('ESCOLAR_SECUNDARIA', 1.00::NUMERIC),
   ('UNIVERSITARIO', 1.00::NUMERIC), ('ADULTO_MAYOR', 1.00::NUMERIC),
   ('DISCAPACIDAD', 1.00::NUMERIC), ('BENEMERITO', 0.00::NUMERIC),
   ('POLICIA_UNIFORMADO', 0.00::NUMERIC)
 ) AS t(categoria, importe)
 WHERE NOT EXISTS (
   SELECT 1 FROM tarifas actual
    WHERE actual.linea_id = l.id AND actual.categoria = t.categoria AND actual.activa
      AND actual.vigente_desde <= CURRENT_DATE
      AND (actual.vigente_hasta IS NULL OR actual.vigente_hasta >= CURRENT_DATE)
 )
ON CONFLICT (linea_id, categoria, vigente_desde) DO NOTHING;

-- Para que el origen de un trasbordo normal no acepte pasajeros nuevos,
-- aplica también este control a la función registrar_abordaje existente:
CREATE OR REPLACE FUNCTION registrar_abordaje(
  p_pasaje_id BIGINT, p_viaje_id BIGINT, p_parada_subida_id BIGINT DEFAULT NULL
) RETURNS BIGINT LANGUAGE plpgsql AS $$
DECLARE
  v_capacidad INTEGER;
  v_ocupacion INTEGER;
  v_estado_viaje VARCHAR(20);
  v_estado_pasaje VARCHAR(25);
  v_abordaje_id BIGINT;
BEGIN
  SELECT m.capacidad_operativa, v.estado INTO v_capacidad, v_estado_viaje
    FROM viajes v JOIN micros m ON m.id = v.micro_id
   WHERE v.id = p_viaje_id FOR UPDATE OF v;
  IF NOT FOUND THEN RAISE EXCEPTION 'No existe el viaje %', p_viaje_id; END IF;
  IF v_estado_viaje <> 'EN_CURSO' THEN RAISE EXCEPTION 'El viaje no esta EN_CURSO'; END IF;
  IF EXISTS (SELECT 1 FROM trasbordos t WHERE t.viaje_origen_id = p_viaje_id
              AND t.tipo = 'NORMAL' AND t.estado = 'ABIERTO') THEN
    RAISE EXCEPTION 'El viaje de origen ya esta en trasbordo y no acepta nuevos abordajes';
  END IF;
  IF v_capacidad IS NULL THEN RAISE EXCEPTION 'Configura la capacidad operativa del micro'; END IF;
  SELECT estado INTO v_estado_pasaje FROM pasajes WHERE id = p_pasaje_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'No existe el pasaje %', p_pasaje_id; END IF;
  IF v_estado_pasaje NOT IN ('PAGADO', 'TRANSFERIDO') THEN
    RAISE EXCEPTION 'El pasaje no esta pagado o habilitado para trasbordo';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pagos p WHERE p.pasaje_id = p_pasaje_id
                  AND p.estado IN ('APROBADO', 'REEMBOLSO_PARCIAL')) THEN
    RAISE EXCEPTION 'El pasaje no tiene pago aprobado o beneficio exento';
  END IF;
  SELECT COUNT(*) INTO v_ocupacion FROM abordajes
   WHERE viaje_id = p_viaje_id AND bajo_en IS NULL;
  IF v_ocupacion >= v_capacidad THEN
    RAISE EXCEPTION 'El micro alcanzo su capacidad operativa (%)', v_capacidad;
  END IF;
  INSERT INTO abordajes (pasaje_id, viaje_id, parada_subida_id)
   VALUES (p_pasaje_id, p_viaje_id, p_parada_subida_id) RETURNING id INTO v_abordaje_id;
  UPDATE pasajes SET estado = 'EN_CURSO', viaje_actual_id = p_viaje_id WHERE id = p_pasaje_id;
  RETURN v_abordaje_id;
END;
$$;

ALTER TABLE trasbordo_pasajes ALTER COLUMN resultado TYPE VARCHAR(30);
ALTER TABLE trasbordo_pasajes DROP CONSTRAINT IF EXISTS trasbordo_pasajes_resultado_check;
ALTER TABLE trasbordo_pasajes ADD CONSTRAINT trasbordo_pasajes_resultado_check
  CHECK (resultado IN ('CONTINUAR', 'CANCELAR_Y_SOLICITAR_REEMBOLSO', 'CANCELAR_SIN_REEMBOLSO'));

COMMIT;
