  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id        INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  categoria         VARCHAR(30) NOT NULL CHECK (categoria IN
                    ('MENOR_12', 'ADULTO_MAYOR', 'DISCAPACIDAD', 'BENEMERITO', 'POLICIA_UNIFORMADO')),
  evidencia_ref     TEXT NOT NULL,
  fecha_nacimiento  DATE,
  estado_validacion VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
                    CHECK (estado_validacion IN ('PENDIENTE', 'APROBADO', 'RECHAZADO')),
  revisado_por      INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
  revisado_en       TIMESTAMPTZ,
  motivo_rechazo    TEXT,
  creado_en         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (usuario_id, categoria),
  CHECK (categoria <> 'MENOR_12' OR fecha_nacimiento IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS beneficios_tarifarios_revision_idx
  ON beneficios_tarifarios(estado_validacion, creado_en);

