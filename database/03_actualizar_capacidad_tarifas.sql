-- Aforo por unidad. La capacidad total debe corresponder al registro/permiso
-- autorizado del vehículo. La recomendación conservadora será solo sentados.
ALTER TABLE micros ADD COLUMN IF NOT EXISTS capacidad_sentados INTEGER;
ALTER TABLE micros ADD COLUMN IF NOT EXISTS capacidad_parados_autorizada INTEGER NOT NULL DEFAULT 0;
ALTER TABLE micros DROP CONSTRAINT IF EXISTS micros_check;
ALTER TABLE micros ADD CONSTRAINT micros_capacidades_detalle_check
  CHECK (capacidad_sentados IS NULL OR
         (capacidad_sentados BETWEEN 1 AND capacidad AND
          capacidad_sentados + capacidad_parados_autorizada = capacidad));
ALTER TABLE micros ADD CONSTRAINT micros_capacidad_parados_check
  CHECK (capacidad_parados_autorizada >= 0);
ALTER TABLE micros ADD CONSTRAINT micros_capacidad_operativa_total_check
  CHECK (capacidad_operativa IS NULL OR capacidad_operativa BETWEEN 1 AND capacidad);

CREATE OR REPLACE FUNCTION fijar_capacidad_operativa_micro()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.capacidad_operativa IS NULL THEN
    NEW.capacidad_operativa := COALESCE(NEW.capacidad_sentados, NEW.capacidad);
  ELSIF NEW.capacidad_operativa > NEW.capacidad THEN
    IF TG_OP = 'UPDATE'
       AND NEW.capacidad_operativa = OLD.capacidad_operativa
       AND NEW.capacidad < OLD.capacidad THEN
      NEW.capacidad_operativa := COALESCE(NEW.capacidad_sentados, NEW.capacidad);
    ELSE
      RAISE EXCEPTION 'La capacidad operativa no puede superar el total autorizado (%)', NEW.capacidad;
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

