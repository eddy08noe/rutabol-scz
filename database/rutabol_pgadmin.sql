CREATE TABLE abordajes (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pasaje_id           BIGINT NOT NULL REFERENCES pasajes(id) ON DELETE RESTRICT,
  viaje_id            BIGINT NOT NULL REFERENCES viajes(id) ON DELETE RESTRICT,
  parada_subida_id    BIGINT REFERENCES paradas(id) ON DELETE SET NULL,
  parada_bajada_id    BIGINT REFERENCES paradas(id) ON DELETE SET NULL,
  subio_en            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  bajo_en             TIMESTAMPTZ,
  CHECK (bajo_en IS NULL OR bajo_en >= subio_en),
  UNIQUE (pasaje_id, viaje_id)
);
CREATE UNIQUE INDEX abordajes_un_pasaje_activo_uq
  ON abordajes(pasaje_id) WHERE bajo_en IS NULL;
CREATE INDEX abordajes_viaje_activos_idx
  ON abordajes(viaje_id) WHERE bajo_en IS NULL;

-- Bloquea el viaje mientras cuenta e inserta, evitando que dos solicitudes
-- simultaneas superen la capacidad operativa.
CREATE FUNCTION registrar_abordaje(
  p_pasaje_id BIGINT,
  p_viaje_id BIGINT,
  p_parada_subida_id BIGINT DEFAULT NULL
) RETURNS BIGINT LANGUAGE plpgsql AS $$
DECLARE
  v_capacidad INTEGER;
  v_ocupacion INTEGER;
  v_estado_viaje VARCHAR(20);
  v_estado_pasaje VARCHAR(25);
  v_abordaje_id BIGINT;
BEGIN
  SELECT m.capacidad_operativa, v.estado
    INTO v_capacidad, v_estado_viaje
    FROM viajes v
    JOIN micros m ON m.id = v.micro_id
   WHERE v.id = p_viaje_id
   FOR UPDATE OF v;

  IF NOT FOUND THEN RAISE EXCEPTION 'No existe el viaje %', p_viaje_id; END IF;
  IF v_estado_viaje <> 'EN_CURSO' THEN RAISE EXCEPTION 'El viaje no esta EN_CURSO'; END IF;
  IF EXISTS (SELECT 1 FROM trasbordos t
              WHERE t.viaje_origen_id = p_viaje_id
                AND t.tipo = 'NORMAL' AND t.estado = 'ABIERTO') THEN
    RAISE EXCEPTION 'El viaje de origen ya esta en trasbordo y no acepta nuevos abordajes';
  END IF;
  IF v_capacidad IS NULL THEN RAISE EXCEPTION 'El micro no tiene capacidad operativa configurada'; END IF;

  SELECT estado INTO v_estado_pasaje FROM pasajes WHERE id = p_pasaje_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'No existe el pasaje %', p_pasaje_id; END IF;
  IF v_estado_pasaje NOT IN ('PAGADO', 'TRANSFERIDO') THEN
    RAISE EXCEPTION 'El pasaje no esta pagado o habilitado para trasbordo';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pagos p WHERE p.pasaje_id = p_pasaje_id
      AND p.estado IN ('APROBADO', 'REEMBOLSO_PARCIAL')
  ) THEN RAISE EXCEPTION 'El pasaje no tiene un pago aprobado'; END IF;

  SELECT COUNT(*) INTO v_ocupacion
    FROM abordajes WHERE viaje_id = p_viaje_id AND bajo_en IS NULL;
  IF v_ocupacion >= v_capacidad THEN RAISE EXCEPTION 'El micro alcanzo su capacidad operativa (%)', v_capacidad; END IF;

  INSERT INTO abordajes (pasaje_id, viaje_id, parada_subida_id)
  VALUES (p_pasaje_id, p_viaje_id, p_parada_subida_id)
  RETURNING id INTO v_abordaje_id;

  UPDATE pasajes SET estado = 'EN_CURSO', viaje_actual_id = p_viaje_id
   WHERE id = p_pasaje_id;
  RETURN v_abordaje_id;
END;
$$;

-- ------------------------ Emergencias y trasbordos -----------------

CREATE TABLE incidentes (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  viaje_id        BIGINT NOT NULL REFERENCES viajes(id) ON DELETE RESTRICT,
  reportado_por   INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
  tipo            VARCHAR(30) NOT NULL
                  CHECK (tipo IN ('FALLA_MECANICA', 'EMERGENCIA_CONDUCTOR', 'OTRA')),
  descripcion     TEXT NOT NULL,
  latitud         NUMERIC(9,6) CHECK (latitud IS NULL OR latitud BETWEEN -90 AND 90),
  longitud        NUMERIC(9,6) CHECK (longitud IS NULL OR longitud BETWEEN -180 AND 180),
  estado          VARCHAR(20) NOT NULL DEFAULT 'ABIERTO'
                  CHECK (estado IN ('ABIERTO', 'RESUELTO', 'CANCELADO')),
  ocurrido_en     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  resuelto_en     TIMESTAMPTZ
);

CREATE TABLE trasbordos (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  viaje_origen_id     BIGINT NOT NULL REFERENCES viajes(id) ON DELETE RESTRICT,
  viaje_destino_id    BIGINT NOT NULL REFERENCES viajes(id) ON DELETE RESTRICT,
  incidente_id        BIGINT REFERENCES incidentes(id) ON DELETE RESTRICT,
  tipo                VARCHAR(15) NOT NULL CHECK (tipo IN ('NORMAL', 'EMERGENCIA')),
  motivo              VARCHAR(30) NOT NULL
                      CHECK (motivo IN ('FIN_TURNO', 'FALLA_MECANICA', 'EMERGENCIA_CONDUCTOR', 'OTRA_EMERGENCIA')),
  registrado_por      INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
  nota                TEXT,
  estado              VARCHAR(20) NOT NULL DEFAULT 'ABIERTO'
                      CHECK (estado IN ('ABIERTO', 'COMPLETADO', 'CANCELADO')),
  creado_en           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (viaje_origen_id <> viaje_destino_id),
  CHECK ((tipo = 'NORMAL' AND motivo = 'FIN_TURNO' AND incidente_id IS NULL)
      OR (tipo = 'EMERGENCIA' AND motivo <> 'FIN_TURNO' AND incidente_id IS NOT NULL))
);

CREATE FUNCTION validar_lineas_trasbordo()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
  v_linea_origen INTEGER;
  v_linea_destino INTEGER;
BEGIN
  SELECT linea_id INTO v_linea_origen FROM viajes WHERE id = NEW.viaje_origen_id;
  SELECT linea_id INTO v_linea_destino FROM viajes WHERE id = NEW.viaje_destino_id;
  IF v_linea_origen IS NULL OR v_linea_destino IS NULL THEN
    RAISE EXCEPTION 'El viaje de origen o destino no existe';
  END IF;

  IF NEW.tipo = 'NORMAL' AND v_linea_origen <> v_linea_destino THEN
    RAISE EXCEPTION 'El trasbordo normal debe ocurrir dentro de la misma linea';
  END IF;

  IF NEW.tipo = 'EMERGENCIA' AND v_linea_origen <> v_linea_destino
     AND NOT EXISTS (
       SELECT 1 FROM convenios_linea c
        WHERE c.activo
          AND c.linea_a_id = LEAST(v_linea_origen, v_linea_destino)
          AND c.linea_b_id = GREATEST(v_linea_origen, v_linea_destino)
     ) THEN
    RAISE EXCEPTION 'El trasbordo entre lineas requiere un convenio activo';
  END IF;

  IF NEW.incidente_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM incidentes i
     WHERE i.id = NEW.incidente_id AND i.viaje_id = NEW.viaje_origen_id
  ) THEN
    RAISE EXCEPTION 'El incidente debe pertenecer al viaje de origen';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trasbordos_validar_lineas_bi
BEFORE INSERT ON trasbordos
FOR EACH ROW EXECUTE FUNCTION validar_lineas_trasbordo();

CREATE TABLE trasbordo_pasajes (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trasbordo_id    BIGINT NOT NULL REFERENCES trasbordos(id) ON DELETE RESTRICT,
  pasaje_id       BIGINT NOT NULL REFERENCES pasajes(id) ON DELETE RESTRICT,
  resultado       VARCHAR(30) NOT NULL DEFAULT 'CONTINUAR'
                  CHECK (resultado IN ('CONTINUAR', 'CANCELAR_Y_SOLICITAR_REEMBOLSO', 'CANCELAR_SIN_REEMBOLSO')),
  registrado_en   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (trasbordo_id, pasaje_id)
);

CREATE TABLE liquidaciones_trasbordo (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trasbordo_id        BIGINT NOT NULL UNIQUE REFERENCES trasbordos(id) ON DELETE RESTRICT,
  linea_origen_id     INTEGER NOT NULL REFERENCES lineas(id) ON DELETE RESTRICT,
  linea_destino_id    INTEGER NOT NULL REFERENCES lineas(id) ON DELETE RESTRICT,
  importe             NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (importe >= 0),
  estado              VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
                      CHECK (estado IN ('PENDIENTE', 'LIQUIDADA', 'NO_APLICA')),
  liquidada_en        TIMESTAMPTZ,
  nota                TEXT,
  CHECK (linea_origen_id <> linea_destino_id)
);

-- ---------------------- Cobros y reembolsos ------------------------

CREATE TABLE pagos (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pasaje_id           BIGINT NOT NULL REFERENCES pasajes(id) ON DELETE RESTRICT,
  viaje_id            BIGINT NOT NULL REFERENCES viajes(id) ON DELETE RESTRICT,
  proveedor           VARCHAR(60) NOT NULL,
  referencia_proveedor VARCHAR(160),
  clave_idempotencia  VARCHAR(255) NOT NULL UNIQUE,
  importe             NUMERIC(10,2) NOT NULL CHECK (importe >= 0),
  metodo              VARCHAR(25) NOT NULL DEFAULT 'TARJETA_SIMULADA'
                      CHECK (metodo IN ('TARJETA_SIMULADA', 'EFECTIVO', 'EXENTO')),
  moneda              CHAR(3) NOT NULL DEFAULT 'BOB' CHECK (moneda = 'BOB'),
  estado              VARCHAR(25) NOT NULL DEFAULT 'PENDIENTE'
                      CHECK (estado IN ('PENDIENTE', 'APROBADO', 'RECHAZADO', 'ANULADO',
                                        'REEMBOLSO_PARCIAL', 'REEMBOLSADO')),
  creado_en           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK ((metodo = 'EXENTO' AND importe = 0) OR (metodo <> 'EXENTO' AND importe > 0))
);
CREATE UNIQUE INDEX pagos_un_cobro_aprobado_por_pasaje_uq
  ON pagos(pasaje_id)
  WHERE estado IN ('APROBADO', 'REEMBOLSO_PARCIAL', 'REEMBOLSADO');
CREATE INDEX pagos_estado_idx ON pagos(estado, creado_en DESC);
CREATE INDEX pagos_viaje_fecha_idx ON pagos(viaje_id, creado_en DESC);

CREATE TABLE reembolsos (
  id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pago_id                 BIGINT NOT NULL REFERENCES pagos(id) ON DELETE RESTRICT,
  referencia_proveedor    VARCHAR(160),
  clave_idempotencia      VARCHAR(255) NOT NULL UNIQUE,
  importe                 NUMERIC(10,2) NOT NULL CHECK (importe > 0),
  motivo                  VARCHAR(40) NOT NULL
                          CHECK (motivo IN ('EMERGENCIA', 'SOLICITADO_POR_PASAJERO', 'OTRO')),
  estado                  VARCHAR(20) NOT NULL DEFAULT 'SOLICITADO'
                          CHECK (estado IN ('SOLICITADO', 'EN_PROCESO', 'CONFIRMADO', 'FALLIDO', 'CANCELADO')),
  solicitado_por          INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
  solicitado_en           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  confirmado_en           TIMESTAMPTZ,
  detalle_error           TEXT
);
