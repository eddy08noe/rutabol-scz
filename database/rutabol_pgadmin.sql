-- La capacidad se registra por unidad según RUAT/registro/autorización.
-- La recomendación conservadora usa solo plazas sentadas; los pasajeros de pie
-- se habilitan únicamente si están autorizados para esa unidad.
CREATE TABLE micros (
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  placa               VARCHAR(20) NOT NULL UNIQUE,
  interno             VARCHAR(20) NOT NULL,
  capacidad           INTEGER NOT NULL CHECK (capacidad BETWEEN 1 AND 100),
  capacidad_sentados  INTEGER,
  capacidad_parados_autorizada INTEGER NOT NULL DEFAULT 0,
  capacidad_operativa INTEGER,
  estado              VARCHAR(20) NOT NULL DEFAULT 'ACTIVO'
                      CHECK (estado IN ('ACTIVO', 'MANTENIMIENTO', 'INACTIVO')),
  linea_id            INTEGER NOT NULL REFERENCES lineas(id) ON DELETE RESTRICT,
  creado_en           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (linea_id, interno),
  UNIQUE (id, linea_id),
  CHECK (capacidad_sentados IS NULL OR capacidad_sentados BETWEEN 1 AND capacidad),
  CHECK (capacidad_parados_autorizada >= 0),
  CHECK (capacidad_sentados IS NULL OR capacidad_sentados + capacidad_parados_autorizada = capacidad),
  CHECK (capacidad_operativa IS NULL OR
         (capacidad_operativa BETWEEN 1 AND capacidad))
);

CREATE FUNCTION fijar_capacidad_operativa_micro()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.capacidad_operativa IS NULL THEN
    NEW.capacidad_operativa := COALESCE(NEW.capacidad_sentados, NEW.capacidad);
  ELSIF NEW.capacidad_operativa > NEW.capacidad THEN
    IF TG_OP = 'UPDATE'
       AND NEW.capacidad_operativa = OLD.capacidad_operativa
       AND NEW.capacidad < OLD.capacidad THEN
      NEW.capacidad_operativa := COALESCE(NEW.capacidad_sentados, NEW.capacidad);
    ELSE
      RAISE EXCEPTION 'La capacidad operativa no puede superar el total autorizado (%)', NEW.capacidad;
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER micros_capacidad_operativa_biud
BEFORE INSERT OR UPDATE ON micros
FOR EACH ROW EXECUTE FUNCTION fijar_capacidad_operativa_micro();

