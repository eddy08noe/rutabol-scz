  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id          INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  linea_id            INTEGER REFERENCES lineas(id) ON DELETE SET NULL,
