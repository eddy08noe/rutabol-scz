  CHECK (latitud IS NULL OR latitud BETWEEN -90 AND 90),
  CHECK (longitud IS NULL OR longitud BETWEEN -180 AND 180)
);

CREATE TABLE linea_paradas (
  linea_id        INTEGER NOT NULL REFERENCES lineas(id) ON DELETE CASCADE,
  parada_id       BIGINT NOT NULL REFERENCES paradas(id) ON DELETE RESTRICT,
  orden           SMALLINT NOT NULL CHECK (orden > 0),
  PRIMARY KEY (linea_id, parada_id),
  UNIQUE (linea_id, orden)
);

CREATE TABLE tarifas (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  linea_id            INTEGER NOT NULL REFERENCES lineas(id) ON DELETE RESTRICT,
  categoria           VARCHAR(20) NOT NULL
  CHECK (categoria IN ('GENERAL', 'MENOR_12', 'ESCOLAR_PRIMARIA', 'ESCOLAR_SECUNDARIA',
                       'UNIVERSITARIO', 'ADULTO_MAYOR', 'DISCAPACIDAD',
                       'BENEMERITO', 'POLICIA_UNIFORMADO')),
  importe             NUMERIC(10,2) NOT NULL CHECK (importe >= 0),
  moneda              CHAR(3) NOT NULL DEFAULT 'BOB' CHECK (moneda = 'BOB'),
  vigente_desde       DATE NOT NULL,
  vigente_hasta       DATE,
  activa              BOOLEAN NOT NULL DEFAULT TRUE,
  creada_por          INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
  creada_en           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (vigente_hasta IS NULL OR vigente_hasta >= vigente_desde),
  UNIQUE (linea_id, categoria, vigente_desde)
);

-- Convenios autorizan trasbordos entre lineas distintas. Los convenios
-- se guardan una sola vez por par, con linea_a_id menor que linea_b_id.
CREATE TABLE convenios_linea (
  linea_a_id      INTEGER NOT NULL REFERENCES lineas(id) ON DELETE RESTRICT,
  linea_b_id      INTEGER NOT NULL REFERENCES lineas(id) ON DELETE RESTRICT,
  activo          BOOLEAN NOT NULL DEFAULT TRUE,
  creado_en       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (linea_a_id, linea_b_id),
  CHECK (linea_a_id < linea_b_id)
);

-- ------------------------- Operación de micros --------------------

CREATE TABLE viajes (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  linea_id        INTEGER NOT NULL REFERENCES lineas(id) ON DELETE RESTRICT,
  micro_id        INTEGER NOT NULL,
  conductor_id    BIGINT NOT NULL REFERENCES conductores(id) ON DELETE RESTRICT,
  estado          VARCHAR(20) NOT NULL DEFAULT 'PROGRAMADO'
                  CHECK (estado IN ('PROGRAMADO', 'EN_CURSO', 'FINALIZADO', 'EMERGENCIA', 'CANCELADO')),
  iniciado_en     TIMESTAMPTZ,
  finalizado_en   TIMESTAMPTZ,
  creado_en       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  FOREIGN KEY (micro_id, linea_id) REFERENCES micros(id, linea_id) ON DELETE RESTRICT,
  CHECK (finalizado_en IS NULL OR iniciado_en IS NULL OR finalizado_en >= iniciado_en)
);

CREATE UNIQUE INDEX viajes_micro_en_curso_uq ON viajes(micro_id) WHERE estado = 'EN_CURSO';
CREATE UNIQUE INDEX viajes_conductor_en_curso_uq ON viajes(conductor_id) WHERE estado = 'EN_CURSO';
CREATE INDEX viajes_linea_estado_idx ON viajes(linea_id, estado);

