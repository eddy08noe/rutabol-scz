-- Reserva importes solicitados/en proceso para que reintentos o solicitudes
-- simultaneas no puedan reembolsar mas que el cobro original.
CREATE FUNCTION validar_tope_reembolso()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
  v_importe_pago NUMERIC(10,2);
  v_estado_pago VARCHAR(25);
  v_importe_reservado NUMERIC(10,2);
  v_excluir_id BIGINT;
BEGIN
  v_excluir_id := NULL;
  IF TG_OP = 'UPDATE' AND NEW.pago_id <> OLD.pago_id THEN
    RAISE EXCEPTION 'No se puede mover un reembolso a otro pago';
  END IF;
  IF TG_OP = 'UPDATE' THEN v_excluir_id := OLD.id; END IF;

  SELECT importe, estado INTO v_importe_pago, v_estado_pago
    FROM pagos WHERE id = NEW.pago_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'No existe el pago %', NEW.pago_id; END IF;
  IF v_estado_pago NOT IN ('APROBADO', 'REEMBOLSO_PARCIAL')
     AND NOT (TG_OP = 'UPDATE' AND v_estado_pago = 'REEMBOLSADO') THEN
    RAISE EXCEPTION 'Solo se reembolsan pagos aprobados o parcialmente reembolsados';
  END IF;

  SELECT COALESCE(SUM(importe), 0) INTO v_importe_reservado
    FROM reembolsos
   WHERE pago_id = NEW.pago_id
     AND estado NOT IN ('FALLIDO', 'CANCELADO')
     AND (v_excluir_id IS NULL OR id <> v_excluir_id);

  IF NEW.estado NOT IN ('FALLIDO', 'CANCELADO') THEN
    v_importe_reservado := v_importe_reservado + NEW.importe;
  END IF;
  IF v_importe_reservado > v_importe_pago THEN
    RAISE EXCEPTION 'El total de reembolsos (%) supera el pago original (%)', v_importe_reservado, v_importe_pago;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER reembolsos_tope_biu
BEFORE INSERT OR UPDATE ON reembolsos
FOR EACH ROW EXECUTE FUNCTION validar_tope_reembolso();

CREATE FUNCTION actualizar_estado_pago_por_reembolsos()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
  v_pago_id BIGINT;
  v_total_confirmado NUMERIC(10,2);
  v_importe_pago NUMERIC(10,2);
BEGIN
  v_pago_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.pago_id ELSE NEW.pago_id END;
  SELECT importe INTO v_importe_pago FROM pagos WHERE id = v_pago_id;
  SELECT COALESCE(SUM(importe), 0) INTO v_total_confirmado
    FROM reembolsos WHERE pago_id = v_pago_id AND estado = 'CONFIRMADO';

  UPDATE pagos
     SET estado = CASE
       WHEN v_total_confirmado >= v_importe_pago THEN 'REEMBOLSADO'
       WHEN v_total_confirmado > 0 THEN 'REEMBOLSO_PARCIAL'
       ELSE 'APROBADO'
     END,
         actualizado_en = NOW()
   WHERE id = v_pago_id AND estado IN ('APROBADO', 'REEMBOLSO_PARCIAL', 'REEMBOLSADO');
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER reembolsos_actualizar_pago_aiud
AFTER INSERT OR UPDATE OR DELETE ON reembolsos
FOR EACH ROW EXECUTE FUNCTION actualizar_estado_pago_por_reembolsos();

