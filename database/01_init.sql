
CREATE TABLE IF NOT EXISTS lineas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL UNIQUE,
  zona VARCHAR(80) NOT NULL,
  descripcion TEXT NOT NULL,
  color VARCHAR(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS micros (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  placa VARCHAR(20) NOT NULL UNIQUE,
  interno VARCHAR(20) NOT NULL UNIQUE,
  capacidad INTEGER NOT NULL CHECK (capacidad BETWEEN 1 AND 100),
  estado VARCHAR(20) NOT NULL CHECK (estado IN ('ACTIVO', 'MANTENIMIENTO', 'INACTIVO')),
  linea_id INTEGER NOT NULL REFERENCES lineas(id)
);

CREATE TABLE IF NOT EXISTS usuarios (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(80) NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  rol VARCHAR(20) NOT NULL DEFAULT 'ADMIN' CHECK (rol = 'ADMIN')
);

